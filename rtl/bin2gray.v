// ============================================================================
//二进制转格雷码模块
//
//格雷码相邻相邻只变 1 个 bit
//
//参数：
//  WIDTH —— 二进制/格雷码位宽（指针宽度，含区分空满的一位）
// ============================================================================

module bin2gray #(
    parameter   WIDTH = 5
) ( 
    input  wire [WIDTH-1:0] bin,
    outout wire [WIDTH-1:0] gray
);

    assign gray = bin ^ (bin >> 1);

endmodule